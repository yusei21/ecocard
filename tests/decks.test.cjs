const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(Boolean);
scripts.forEach((script,i)=>{new vm.Script(script,{filename:'index-inline-'+i+'.js'})});
const start=html.indexOf('const SUITS='),end=html.indexOf('function cardHTML(');
assert(start>=0&&end>start,'card model must exist');
const snippet=html.slice(start,end);
const ctx=vm.createContext({Math,console});
vm.runInContext(snippet,ctx);
const solo=vm.runInContext('makeDeck(1)',ctx);
const multi=vm.runInContext('makeDeck(2)',ctx);
assert.equal(solo.length,65);
assert.equal(multi.length,130);
assert.equal(new Set(solo.map(c=>c.id)).size,65);
assert.equal(new Set(multi.map(c=>c.id)).size,130);
assert.equal(new Set(solo.map(c=>c.suit)).size,5);
for(const suit of ['azul','vermelho','verde','amarelo','marrom']){
 const cards=solo.filter(c=>c.suit===suit);
 assert.equal(cards.length,13);
 assert.equal(cards.map(c=>c.rank).sort((a,b)=>a-b).join(','),Array.from({length:13},(_,i)=>i+1).join(','));
}
assert.equal(vm.runInContext('cardRank(1)',ctx),'A');
assert.equal(vm.runInContext('cardRank(11)',ctx),'J');
assert.equal(vm.runInContext('cardRank(12)',ctx),'Q');
assert.equal(vm.runInContext('cardRank(13)',ctx),'K');
assert(html.includes('room.deck=makeDeck(2)'), 'multiplayer must deal from 2 decks');
assert(html.includes('ifma-logo'), 'institutional mark must be present');
const logic=html.slice(html.indexOf('function validMeld('),html.indexOf('function cleanMulti('));
vm.runInContext(logic,ctx);
const C=(rank,suit='azul',id=rank+'-'+suit)=>({rank,suit,id});
const meld=cards=>vm.runInContext('validMeld('+JSON.stringify(cards)+')',ctx);
const win=cards=>vm.runInContext('hasWin('+JSON.stringify(cards)+')',ctx);
assert(meld([C(1),C(2),C(3)]),'A-2-3 must be valid');
assert(meld([C(12),C(13),C(1)]),'Q-K-A must be valid');
assert(!meld([C(13),C(1),C(2)]),'K-A-2 must not wrap around');
assert(meld([C(3,'azul'),C(3,'verde'),C(3,'marrom')]),'three equal ranks valid');
assert(meld([C(3,'azul','one'),C(3,'azul','two'),C(3,'verde','three')]),'two-deck physical copies allowed');
assert(!meld([C(3,'azul','same'),C(3,'azul','same'),C(3,'verde','other')]),'cannot reuse physical card');
assert(!meld([C(1,'azul'),C(2,'verde'),C(3,'azul')]),'runs must share suit');
const nine=[C(3,'azul','a'),C(3,'verde','b'),C(3,'marrom','c'),C(2,'azul','d'),C(2,'verde','e'),C(2,'marrom','f'),C(13,'azul','g'),C(13,'verde','h'),C(13,'marrom','i')];
assert(win(nine),'three independent sets of three should win');
assert(!win(nine.slice(0,7)),'seven cards must not win');
assert(!win(nine.slice(0,8)),'eight cards must not win');
assert(!win([...nine,C(8,'amarelo','j')]),'must discard tenth card first');
const highAce=[C(1,'azul','1'),C(2,'azul','2'),C(3,'azul','3'),C(12,'verde','4'),C(13,'verde','5'),C(1,'verde','6'),C(8,'marrom','7'),C(8,'verde','8'),C(8,'azul','9')];
assert(win(highAce),'A-2-3 plus Q-K-A plus three 8s should win');
assert(html.includes('i<9;i++'),'each player starts with nine cards');
assert(html.includes('p.hand.length!==10'),'turn ends by discarding tenth card');
console.log('✓ Three trincas, nine cards, Ace low/high and win conditions passed');
console.log('✓ 65-card solo, 130-card multiplayer, five A–K suits and inline JS syntax verified');
